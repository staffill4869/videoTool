  defp pipeline_summary(steps, ticks) do
    here = Enum.find(steps, &(&1.state != :done and &1.state != :wait))

    case here do
      nil -> "여덟 칸 모두 끝남"
      %{name: name, state: state} -> "여덟 칸 중 #{ticks}칸 끝남. #{name} #{state_ko(state)}."
    end
  end

