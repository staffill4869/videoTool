alias VideoTool.Repo
alias VideoTool.Presets.DomainPreset

put = fn attrs ->
  row = Repo.get_by(DomainPreset, slug: attrs.slug) || %DomainPreset{}
  {:ok, d} = row |> DomainPreset.changeset(attrs) |> Repo.insert_or_update()
  IO.puts("  #{d.slug}  #{d.name}")
end

