# 지원사업 화풍을 **아이소메트릭 로우폴리로 되돌린다.**
# 미니어처 사진으로 바꿔 봤더니 결과물 품질이 떨어졌다 (사용자 판단, 2026-10-02).
# 이름만 적으면 Flow 가 편마다 다르게 해석하므로, 항목으로 적는 방식은 유지한다.

import Ecto.Query
alias VideoTool.Repo

style = """
GLOBAL STYLE
아이소메트릭 로우폴리 디오라마. 아래 항목을 매 컷 똑같이 지켜라.

재질   무광 평면. 질감 노이즈를 넣지 마라. 모서리는 또렷하게.
선     윤곽선을 그리지 마라. 형태는 면과 그림자로 구분한다.
조명   45도에서 오는 따뜻한 주광 하나. 부드러운 음영(ambient occlusion).
색     파스텔 톤으로 낮춘 색. 네온·발광·고채도 금지.
구성   장면마다 받침판 위에 올린 하나의 완결된 디오라마.
금지   홀로그램, 회로 무늬, 떠 있는 아이콘, 데이터 그래프 벽, SF 패널, 실사 사진풍.

**화면을 꽉 채운다.** 디오라마를 가운데 작게 놓고 주위를 비우지 마라 —
세로 화면에서 그러면 빈 배경이 절반을 먹고 싸구려로 보인다(2026-09-30 실측).
받침판 가장자리가 화면 좌우 끝에 닿게, 위아래로도 프레임을 채우게 잡는다.
자막과 라벨은 합성 단계에서 위에 겹쳐 구우므로 글자 자리를 비워 둘 필요가 없다.
"""

assets = """
여러 컷에 반복 등장하는 대상은 첫 등장 때의 형태·색·비율을 그대로 유지한다.
"""

now = DateTime.utc_now() |> DateTime.truncate(:second)

{n, _} =
  from(s in "style_presets", where: s.id == 2)
  |> Repo.update_all(set: [global_style: style, asset_definitions: assets, updated_at: now])

IO.puts("지원사업 화풍 복구: #{n}건")
