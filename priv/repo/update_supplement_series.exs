# 영양제 시리즈: 목소리를 Harrison 으로, 대본 말투를 "재미있게" 로 다시 짠다.
#
# 말투 지시를 `standing_prompt` 가 아니라 `topic_brief` 에 넣는다.
# standing_prompt 는 Flow 상시 지시로도 내려가서 **그림 생성에 섞인다** —
# 거기에 "웃기게 써라" 를 넣으면 이미지가 우스꽝스러워진다. 말투는 대본만의 일이다.

alias VideoTool.{Repo, Series}

brief = """
영양제와 몸의 작동 원리를 하나씩 푼다. 제품 추천, 브랜드, 구매 유도는 하지 않는다.
"왜 그렇게 되는가" 를 몸의 구조로 설명한다 — 흡수, 배출, 경쟁, 타이밍, 형태.

말투 — 담백한 다큐 톤으로 가되, 한 편에 두세 번 툭 치고 빠진다.
개그를 욕심내지 마라. 설명이 먼저고 웃음은 그 위에 얹히는 것이다.

쓸 수 있는 장치 세 가지:
1) 몸속을 일터처럼 그린다. 운반체는 자리가 정해진 엘리베이터고, 간은 재고를 받는 창고이며,
   위산은 입구에서 아무나 못 들어오게 막는 쪽이다. 억지로 의인화하지 말고,
   실제 작동이 정말 그렇게 생겼을 때만 쓴다.
2) 흔한 오해를 **진지하게 먼저 말하고** 뒤집는다.
   "많이 먹으면 많이 흡수될 것 같다. 몸은 그렇게 안 세어 본다."
3) 기대와 실제의 낙차를 짚는다.
   "먹고 다음 날 개운했다면, 그건 영양제가 아니라 잠일 확률이 높다."

하지 말 것
- 말장난 남발, 유행어, 이모지, "여러분~" 같은 방송 말투
- 효능 과장, 단정적인 건강 조언, 근거 없는 수치
- 웃기려고 사실을 비트는 것. 웃음보다 정확이 먼저다
- 자학이나 비꼼. 보는 사람을 놀리지 않는다

구조는 그대로다. 8장면, 장면마다 공백 제외 38~42자, 마지막 장면은 질문으로 닫는다.
첫 장면은 "다들 겪어 봤을 장면" 으로 연다 — 설명이 아니라 상황으로 시작한다.
"""

{:ok, series} = Series.get(4)

{:ok, updated} =
  Series.update(series, %{
    # Harrison — 남성. 목소리를 시리즈마다 달리해 채널이 귀로 구분되게 한다.
    voice_id: 95,
    topic_brief: String.trim(brief)
  })

IO.puts("영양제 시리즈 갱신: voice_id=#{updated.voice_id}, brief #{String.length(updated.topic_brief)}자")
