# 건강·영양 장르를 추가한다.
#
# 이 장르는 다른 장르와 성격이 다르다 — 사람 몸에 넣는 것을 다루므로
# "효과가 있다" 로 읽히는 표현이 곧 위험이다. 그래서 규칙 대부분이 금지 쪽이다.
# 유튜브·인스타 모두 건강 주장에 대한 정책이 따로 있고, 과장 표기는 계정 단위로 문제가 된다.

alias VideoTool.Repo
alias VideoTool.Presets.DomainPreset

upsert = fn schema, keys, attrs ->
  case Repo.get_by(schema, keys) do
    nil -> struct(schema) |> schema.changeset(attrs) |> Repo.insert!()
    row -> row |> schema.changeset(attrs) |> Repo.update!()
  end
end

upsert.(DomainPreset, [slug: "health-nutrition"], %{
  name: "건강·영양",
  slug: "health-nutrition",
  info_rules: """
  건강·영양 특화 기준
  - 치료·예방·완치로 읽히는 표현을 쓰지 않는다. 이건 표현 문제가 아니라 규정 문제다
  - 수치(함량, 권장량, 상한량)는 반드시 단위와 함께 쓰고, 허용 목록에 있는 것만 쓴다
  - 제품명·브랜드·로고를 넣지 않는다. 일반명(성분명)만 쓴다
  - 사람 몸을 그릴 때 특정 질환의 환부를 사실적으로 묘사하지 않는다. 구조 도해로 대신한다
  - 흡수·대사 경로는 실선 화살표, 추정·조건부 경로는 점선으로 구분한다
  - 개인차가 있는 내용에는 "개인차" 표시를 남긴다
  """,
  element_list: """
  사용 가능 요소: 분자 구조 모형, 장기 단면 도해, 흡수 경로 화살표, 농도 그래프,
  시간축 타임라인, 권장량 막대, 비교 막대, 단위 라벨, 범례, 단계 번호(원형 배지),
  강조 외곽선, 개인차 표시
  금지 요소: 제품 패키지, 브랜드 로고, 알약 클로즈업의 상표면, 전후 비교 사진,
  인물 체형 비교, 효과를 단정하는 체크·별점 그래픽
  """,
  color_semantics: %{
    "성분" => "시안",
    "흡수" => "초록",
    "배출" => "주황",
    "결핍" => "빨강",
    "권장량" => "파랑",
    "상한량" => "마젠타",
    "중립" => "회색"
  },
  video_topic_rules: """
  주제별 자동 적용
  - 흡수 경로: 입 → 위 → 소장 → 혈류 순서로 카메라가 따라가며 경로선이 뻗는다
  - 농도 변화: 시간축을 따라 곡선이 그려지고 권장량·상한량 선이 기준으로 깔린다
  - 결핍과 과잉: 같은 축에 양쪽을 놓고 가운데 안전 구간을 밝게 둔다
  - 성분 비교: 같은 축척 막대로 나란히. 축척이 다르면 축척 표시를 넣는다
  """
})

IO.puts("건강·영양 장르 저장 완료")

for d <- Repo.all(DomainPreset) do
  IO.puts("  #{d.slug}  #{d.name}")
end
