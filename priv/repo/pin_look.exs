# 화풍과 인물 생김새를 **글로 못 박는다.**
#
# 그 전에는 global_style 이 "infographic-3d 화풍으로 그린다" 한 줄이었다.
# 그게 뭔지 적혀 있지 않으니 Flow 가 편마다 다르게 해석했고, 실제로
# 같은 시리즈 안에서 배경이 밝은 방 → 네온 회로 → 어두운 스튜디오로 튀었다
# (2026-10-01, 135번에 HUD 다이어그램이 깔림).
#
# 화풍은 **이름이 아니라 항목으로** 적어야 재현된다.

import Ecto.Query
alias VideoTool.Repo

style = """
GLOBAL STYLE
3D 렌더 인포그래픽. 아래 항목을 **매 컷 똑같이** 지켜라.
한 항목이라도 바뀌면 같은 영상으로 안 보인다.

재질   매끄러운 무광 표면. 거친 질감·천 올·피부 모공을 넣지 마라.
       금속 광택, 유리 반사, 젖은 표면 같은 고광택을 쓰지 마라.
선     윤곽선을 그리지 마라. 형태는 면과 그림자로만 구분한다.
조명   위 앞쪽에서 오는 부드럽고 큰 광원 하나. 그림자는 옅고 가장자리가 부드럽다.
       역광, 네온 발광, 렌즈 플레어, 빛줄기, 반짝임을 넣지 마라.
색     밝은 중간톤. 배경은 연회백색·연베이지·연하늘 중 하나로 한다.
       검은 배경, 짙은 남색 배경, 어두운 스튜디오를 쓰지 마라.
배경   실제로 있을 법한 방·주방·사무실·거리. 홀로그램 화면, 회로 무늬,
       떠 있는 아이콘, 데이터 그래프 벽, SF 패널을 배경에 넣지 마라.
카메라 눈높이에서 본 모습. 어안·광각 왜곡을 쓰지 마라.
비율   사람은 실제 비율(7등신)로 그린다. 머리를 크게 만들거나 인형처럼 만들지 마라.
"""

assets = """
여러 컷에 반복 등장하는 대상은 첫 등장 때의 형태·색·비율을 그대로 유지한다.

**사람은 특히 그렇다.** 아래 항목은 매 컷, 매 편 같아야 한다 —
얼굴 생김새, 머리 모양과 색, 안경 유무와 테 모양, 옷의 종류와 색, 신발 색, 키 차이.
한 편 안에서도 컷마다 얼굴이 달라지면 다른 사람으로 보인다.
옷을 갈아입히지 마라. 머리를 풀거나 묶지 마라. 안경을 벗기지 마라.
"""

{n, _} =
  from(s in "style_presets", where: s.id == 19)
  |> Repo.update_all(set: [global_style: style, asset_definitions: assets, updated_at: DateTime.utc_now() |> DateTime.truncate(:second)])

IO.puts("화풍 갱신: #{n}건")

people = """
같은 인물 두 명이 매 편 나온다. **생김새를 편마다 바꾸지 마라.**

민호 — 30대 중반 한국인 남성. 키는 서윤보다 한 뼘 크다.
  짧고 단정한 검은 머리(가르마 없음), 둥근 검은 뿔테 안경,
  연회색 후드티(지퍼 없음), 짙은 남색 긴바지, 회색 운동화.
  늘 성실하게 챙겨 먹지만 방법이 한 끗 틀려 있는 쪽이다.

서윤 — 30대 중반 한국인 여성.
  뒤로 하나로 묶은 검은 머리(앞머리 없음), 안경 없음,
  남색 니트, 베이지색 긴바지, 흰 운동화.
  같은 것을 먹는데 결과가 다른 쪽이다. 먼저 알려주지 않는다.

둘 다 안경·머리·옷을 **한 편 안에서도, 편이 바뀌어도** 그대로 둔다.
갈아입히거나 머리를 바꾸면 다른 사람으로 보인다.

두 사람은 말풍선이나 글자 없이 **표정과 몸짓**으로만 드러낸다.
화면에 글자를 만들지 마라.
"""

{m, _} =
  from(s in "series", where: s.id == 4)
  |> Repo.update_all(set: [standing_prompt: people, updated_at: DateTime.utc_now() |> DateTime.truncate(:second)])

IO.puts("인물 갱신: #{m}건")
