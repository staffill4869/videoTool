# 영양제 시리즈 인물 규칙을 고친다 (사용자 지시 2026-10-02).
#
# 지금까지는 **늘 민호가 틀리고 서윤이 맞았다.** 같은 구도가 반복되면 식상하고,
# 민호 쪽에 감정이입한 사람은 매번 지는 편을 보게 된다.
# 그리고 두 명이 꼭 같이 나올 필요가 없다 — 여성용 영양제는 서윤만, 남성용은 민호만 나오면 된다.

import Ecto.Query
alias VideoTool.Repo

people = """
같은 인물 두 명이 시리즈에 나온다. **생김새를 편마다 바꾸지 마라.**

민호 — 30대 중반 한국인 남성. 키는 서윤보다 한 뼘 크다.
  짧고 단정한 검은 머리(가르마 없음), 둥근 검은 뿔테 안경,
  연회색 후드티(지퍼 없음), 짙은 남색 긴바지, 회색 운동화.

서윤 — 30대 중반 한국인 여성.
  뒤로 하나로 묶은 검은 머리(앞머리 없음), 안경 없음,
  남색 니트, 베이지색 긴바지, 흰 운동화.

둘 다 안경·머리·옷을 **한 편 안에서도, 편이 바뀌어도** 그대로 둔다.
갈아입히거나 머리를 바꾸면 다른 사람으로 보인다.

**누가 틀리는지는 편마다 바꾼다.**
지금까지 늘 민호가 잘못 먹고 서윤이 제대로 먹는 구도였다 — 그게 반복되면 식상하다.
이번 편에서 민호가 틀렸으면 다음 편에서는 서윤이 틀리게 쓴다. 번갈아 간다.

**두 명이 꼭 같이 나올 필요는 없다.**
여성에게 해당하는 영양제(철분·엽산·칼슘 등)는 **서윤만** 나오게 쓴다.
남성에게 해당하는 것(아연·전립선·단백질 등)은 **민호만** 나오게 쓴다.
주제가 남녀 공통이면 둘을 비교하는 구도로 쓴다.
한 사람만 나오는 편에서는 그 사람의 하루 안에서 앞뒤가 갈리게 만든다
(예: 아침에 이렇게 먹던 사람이 방법을 바꾼 뒤 달라졌다).

두 사람은 말풍선이나 글자 없이 **표정과 몸짓**으로만 드러낸다.
화면에 글자를 만들지 마라.
"""

{n, _} =
  from(s in "series", where: s.id == 4)
  |> Repo.update_all(
    set: [standing_prompt: people, updated_at: DateTime.utc_now() |> DateTime.truncate(:second)]
  )

IO.puts("영양제 인물 규칙 갱신: #{n}건")
