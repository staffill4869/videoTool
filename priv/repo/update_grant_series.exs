# 임실군 안전키트, 성주군 외식업소, 의성군 웰컴키즈존, 예천군 IoT, 군산시 상생카드.
# 임실군 인구가 2만 7천이다. 그중 해당 업체는 수백 곳이고, 그 수백 명이 쇼츠를
# 볼 확률까지 곱하면 조회수 4 는 영상이 못 만들어서 나온 숫자가 아니다.
# 세종 통근버스 편은 공고문에 "딱 2개사" 라고 적혀 있었다. 2명을 위한 영상이었다.
#
# 그리고 `standing_prompt` 에 에이전트 작업 지시가 들어 있었다. 이 필드는
# **Flow 이미지 프롬프트 뒤에 그대로 붙는다** (flow.ex:163 · prompt.ex:137).
# 즉 그림을 그릴 때마다 "list_grants 로 공고를 보고 한 건을 고른다" 가 같이 들어갔다.
# 작업 지시는 topic_brief 로 옮기고 이 칸은 비운다.

alias VideoTool.{Repo, Series}

brief = """
기업마당 지원사업 공고를 하나씩 풀어, 누가 얼마를 언제까지 받을 수 있는지 알려주는 시리즈.

## 주제 고르기 — 여기서 조회수가 갈린다

`list_grants` 목록에서 고를 때 **볼 사람이 몇 명인지 먼저 센다.**

쓰지 않는다
- **군(郡) 단위 공고.** 제목이 `[경북] 의성군 ...`, `[전북] 임실군 ...` 처럼
  군 이름으로 좁혀지는 것. 인구 2~5만이라 해당 업체가 수백 곳뿐이다.
  실측으로 조회수 4~16 이 나왔다
- 대상이 몇 곳으로 못 박힌 것. 공고문에 "2개사", "선착순 5개소" 가 있으면 버린다
- **마감이 2주 안에 오는 것.** 쇼츠는 올린 뒤 며칠에 걸쳐 조회수가 붙는데
  마감이 지나면 그 뒤로는 아무 쓸모가 없는 영상이 된다 (의성군 편은 올린 지 사흘 만에 마감이었다).
  `ends_on` 을 보고 2주 넘게 남았거나 「상시」·「예산 소진시까지」 인 것을 고른다.
  **3주로 잡지 마라** — 전국 공고 중 3주 넘게 남은 건 좁은 R&D 과제뿐이라
  결국 청중이 작은 쪽으로 되돌아간다 (2026-09-30 실측: 중앙부처 공고 14건 중 3주 이상은 2건).

고르는 순서
1. 중앙부처 (중소벤처기업부·산업통상부·과기정통부·농림축산식품부·고용노동부 …) — 전국이 대상이다
2. 광역시·도 전체를 대상으로 하는 것 (`[경남] 2026년 중소기업 해외인증 획득 지원` 처럼
   군·시 이름이 안 붙은 것)
3. 서울·부산·대구·인천 같은 큰 시

한 건도 안 맞으면 `list_grants(limit: 60)` 로 더 받아서 다시 고른다.
군 단위 공고로 채우느니 그 회차를 건너뛰는 게 낫다.

## 무엇을 말할 것인가

공고를 읽어 주는 영상이 아니다. **못 받는 사람도 끝까지 보는 영상**이어야 한다.
자격이 안 되는 사람에게도 "이런 돈이 나온다는 건 몰랐네" 가 남아야 조회수가 붙는다.

- 첫 장면은 **돈**이나 **놀라운 사실**로 연다. 기관 이름·공고 이름으로 열지 마라.
  나쁨: "중소벤처기업부가 딥테크 챌린지 프로젝트 공고를 냈습니다"
  좋음: "한 곳에 90억을 줍니다. 그런데 조건이 하나 붙습니다"
- 지역은 말하되 **첫 문장에 넣지 마라.** 지역 이름이 먼저 나오면
  거기 사는 사람이 아닌 시청자는 그 자리에서 넘긴다. 세 번째 장면쯤에서 밝힌다
- 마지막 장면은 질문으로 닫는다

## 제목

- **돈이나 혜택이 맨 앞에.** 지역·기관 이름을 앞에 두지 마라
  나쁨: `예천군 소규모 사업장 측정기기 부착 지원, 60% 보조`
  좋음: `설비값 60%를 나라가 냅니다`
- 시리즈 이름과 회차 번호(`| 지원사업, 지금 받는 곳 #7`)를 붙이지 마라.
  쇼츠는 제목이 한 줄에서 잘린다. 그 자리를 관리용 번호에 쓰면 손해다
- 30자 안쪽

## 해시태그

지역 이름(#임실군)은 넣지 마라 — 아무도 안 찾는다.
`#정부지원사업 #소상공인 #창업지원 #중소기업` 처럼 찾는 사람이 있는 말로 넣는다.

## 사실 확인

`attachment`(첨부 공고문)를 열어 지원금액·대상·마감일을 확인하고 `save_allowed_facts` 에 넣는다.
요약(`summary`)에 없는 숫자는 쓰지 않는다 — 요약만 보고 쓰면 지어낸 값이 나간다.

구조는 그대로다. 8장면, 마지막 장면은 질문으로 닫는다.
