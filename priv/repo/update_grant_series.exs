# 지원사업 시리즈(7). 조회수가 영양제의 1/30 이라 두 군데를 고친다.
#
# 실측 (09-30 기준, 편당 조회수):
#   영양제  178 · 262 · 307 · 338 · 378 · 419 · 669 · 1007 · 1053 · 1318 · 1342
#   지원사업  4 ·  4 ·  5 ·  15 ·  15 ·  16 ·  82
