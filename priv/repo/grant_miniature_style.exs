# 지원사업 시리즈 화풍을 **미니어처 사진**으로 바꾼다.
#
# 전에는 "Isometric low-poly diorama" 였다. 깔끔하지만 장난감 블록처럼 보여
# 눈길을 못 끈다. 미니어처는 "진짜 사진인데 사람만 작다" 는 위화감이 있어
# 손가락을 멈추게 한다 — 쇼츠에서 그게 전부다.
#
# 화풍은 **이름이 아니라 항목으로** 적는다. "미니어처로 그려라" 한 줄이면
# Flow 가 편마다 다르게 해석한다 (영양제에서 실제로 겪었다).

import Ecto.Query
alias VideoTool.Repo

style = """
GLOBAL STYLE
**미니어처 사진.** 실제로 찍은 사진처럼 보여야 한다. 그림체·일러스트·3D 렌더처럼 보이면 안 된다.
아래 항목을 매 컷 똑같이 지켜라.

사람    키 1~2cm 짜리 **미니어처 인형**. 작업복·안전모·앞치마 같은 차림이 또렷하다.
        얼굴은 작아서 이목구비가 거의 안 보인다. 실물 크기 사람을 그리지 마라.
사물    사람 말고는 **전부 실제 크기 실물**이다 — 서류, 동전, 영수증, 열쇠, 공구, 음식.
        인형이 그 위를 오르내리고 사다리를 걸치고 밀고 나른다. 크기 차이가 커야 재미있다.
렌즈    접사 렌즈로 비스듬히 본 모습. **얕은 심도** — 가운데만 또렷하고 위아래는 부드럽게 번진다.
        틸트 시프트 느낌. 화면 전체가 또렷하면 미니어처로 안 보인다.
조명    창가 자연광. 부드러운 그림자가 한쪽으로 길게 눕는다. 스튜디오 조명·역광·네온 금지.
색      실제 사물의 색 그대로. 채도를 과하게 올리지 말고, 인형의 옷만 또렷한 색으로 둔다.
배경    바로 뒤는 흐릿하게 날린다. 흰 배경·단색 배경·그라데이션 판을 쓰지 마라.
금지    홀로그램, 회로 무늬, 떠 있는 아이콘, 데이터 그래프 벽, SF 패널, 발광 효과.

**화면을 꽉 채운다.** 가운데 작게 놓고 주위를 비우지 마라 —
세로 화면에서 그러면 빈 배경이 절반을 먹고 싸구려로 보인다(2026-09-30 실측).
네 변 끝까지 사진이 이어지게 잡는다. 자막 자리를 비워 둘 필요는 없다 —
자막과 라벨은 합성 단계에서 위에 겹쳐 굽는다.
"""

assets = """
여러 컷에 반복 등장하는 대상은 첫 등장 때의 형태·색·비율을 그대로 유지한다.
미니어처 인형의 옷 색과 안전모 색도 편 안에서 바꾸지 마라 — 같은 사람으로 읽혀야 한다.
"""

now = DateTime.utc_now() |> DateTime.truncate(:second)

{n, _} =
  from(s in "style_presets", where: s.id == 2)
  |> Repo.update_all(set: [global_style: style, asset_definitions: assets, updated_at: now])

IO.puts("지원사업 화풍 갱신: #{n}건")
